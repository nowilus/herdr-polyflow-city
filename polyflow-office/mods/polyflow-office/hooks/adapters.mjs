// What a Claude Code or Codex session file says, as the chat's conversation. One adapter per program, both giving
// the same messages:
//   { id, role: "user" | "assistant" | "note", text, at }
//   { id, role: "tool", text: "Edit index.ts", at, files: [{ path, verb: "edited" | "read" }],
//     status: "running" | "ok" | "error", output }
// `id` is the source's own id (a message uuid, a tool call id) where there is one. `files` keep full paths: the
// chat shows them to the person on their own machine (the activity hook, which writes files, keeps base names only).
// A tool's result is folded into its call, so a failed edit says so. Lines it doesn't know are skipped: a new
// format shows less, never breaks.
// Reader v2 adds, without changing the above: on a tool message `startedAt` / `finishedAt` (ms, from the lines' own
// times; null when unknown) and `cwd` (the folder it ran in); and next to `messages` the explicit `plan` and the
// `session` (model, tokens), collected over every line read, not just the messages kept (hooks/session-meta.mjs).
import { commandHead, targetOf } from "./activity.mjs";
import { createPlanTracker, createUsageTracker, toMs } from "./session-meta.mjs";

export const KEEP = 400;
const TEXT_MAX = 40000;
const OUTPUT_MAX = 2000;

const EDIT_TOOLS = /^(edit|write|multiedit|notebookedit|write_file|create_file|str_replace_editor)$/i;
const READ_TOOLS = /^(read|notebookread|view_image|read_file)$/i;

// What the agent's harness writes into the person's turn: whole blocks cut out wherever they are.
const BLOCKS = /<(system-reminder|command-name|command-message|command-args|local-command-stdout|local-command-stderr|local-command-caveat|environment_context|user_instructions|turn_aborted|task-notification|user-prompt-submit-hook|bash-input|bash-stdout|bash-stderr|INSTRUCTIONS)>[\s\S]*?<\/\1>/g;
// Whole messages the harness sends as the person (judged by their first line).
const HARNESS_ONLY = /^(# AGENTS\.md instructions\b|Caveat: The messages below were generated by the user)/;
const HC_FROM = /^<hc from="([^"]{1,80})">([\s\S]*)<\/hc>$/;
const INTERRUPTED = /^\[Request interrupted by user[^\]]*\]$/;

const clip = (s, max = TEXT_MAX) => (s.length > max ? `${s.slice(0, max)}…` : s);
const baseName = (p) => p.split(/[\\/]/).filter(Boolean).pop() ?? p;

function safeJson(s) {
  try {
    return JSON.parse(s);
  } catch {
    return null;
  }
}

// What the person typed, without the harness's blocks; "" when nothing of theirs is left.
export function userText(raw) {
  if (typeof raw !== "string") return "";
  const text = raw.replace(BLOCKS, "").trim();
  return HARNESS_ONLY.test(text.split("\n")[0]) ? "" : text;
}

// The files an apply_patch text names, in order: Update / Add / Delete File and Move to.
export function patchFiles(patch) {
  if (typeof patch !== "string") return [];
  return [...patch.matchAll(/^\*\*\* (?:Update File|Add File|Delete File|Move to): (.+?)\s*$/gm)].map((m) => m[1]);
}

// A string literal from JS source ("C:\\\\x" -> "C:\\x"); null if it isn't one.
const literal = (s) => (typeof s === "string" ? safeJson(`"${s.replace(/\r/g, "\\r").replace(/\n/g, "\\n").replace(/\t/g, "\\t")}"`) : null);

// A tool call -> { text, files }.
function describe(name, input) {
  const args = typeof input === "string" ? safeJson(input) ?? input : input;
  // Codex code cells: the tools they call are in the source.
  if (name === "exec" && typeof args === "string") return describeCell(args);
  if (/apply_patch/i.test(name)) {
    const files = patchFiles(typeof args === "string" ? args : args?.input ?? args?.patch ?? "");
    return { text: files.length ? `Edit ${files.map(baseName).join(", ")}` : "Edit (patch)", files: files.map((path) => ({ path, verb: "edited" })) };
  }
  const i = args !== null && typeof args === "object" ? args : {};
  const path = [i.file_path, i.notebook_path, i.path].find((p) => typeof p === "string" && p !== "");
  const verb = EDIT_TOOLS.test(name) ? "edited" : READ_TOOLS.test(name) ? "read" : null;
  const target = targetOf(Array.isArray(i.command) ? { ...i, command: i.command.join(" ") } : i);
  return { text: target ? `${name} ${target}` : String(name), files: verb && path ? [{ path, verb }] : [] };
}

// A command's first real line: a PowerShell here-string (@' ... '@ | ...) is named by what it holds.
const firstLine = (cmd) => cmd.replace(/^\s*@['"]\s*\r?\n/, "").split(/\r?\n/).find((l) => l.trim() !== "") ?? "";

function describeCell(src) {
  const patch = [...src.matchAll(/apply_patch\(\s*"((?:[^"\\]|\\.)*)"/g)].map((m) => literal(m[1]) ?? "").join("\n");
  const edited = patchFiles(patch);
  const commands = [...src.matchAll(/exec_command\(\s*\{\s*cmd\s*:\s*"((?:[^"\\]|\\.)*)"/g)].map((m) => commandHead(firstLine(literal(m[1]) ?? ""))).filter(Boolean);
  const viewed = [...src.matchAll(/view_image\(\s*\{\s*path\s*:\s*"((?:[^"\\]|\\.)*)"/g)].map((m) => literal(m[1])).filter(Boolean);
  const files = [...edited.map((path) => ({ path, verb: "edited" })), ...viewed.map((path) => ({ path, verb: "read" }))];
  const text = edited.length ? `Edit ${edited.map(baseName).join(", ")}`
    : commands.length ? `Run ${commands.join(" · ")}`
    : viewed.length ? `View ${viewed.map(baseName).join(", ")}`
    : "exec";
  return { text, files };
}

// Codex results: text pieces of a string, an array of input_text or a JSON { output, metadata: { exit_code } }.
function codexResult(output) {
  const parts = Array.isArray(output) ? output.filter((o) => o?.type === "input_text").map((o) => o.text) : [String(output ?? "")];
  const raw = parts.join("\n");
  const json = parts.length === 1 ? safeJson(raw) : null;
  const text = typeof json?.output === "string" ? json.output : raw;
  const exit = json?.metadata?.exit_code;
  const cell = raw.match(/^Script running with cell ID (\S+)/);
  const failed = /^Script failed/.test(raw) || /\nScript error:/.test(`\n${raw}`) || (typeof exit === "number" && exit !== 0);
  return { status: cell ? "running" : failed ? "error" : "ok", text, cell: cell?.[1] ?? null };
}

const claudeResultText = (content) => (typeof content === "string" ? content
  : Array.isArray(content) ? content.filter((b) => b?.type === "text").map((b) => b.text).join("\n") : "").replace(/<\/?tool_use_error>/g, "");

// The folder a tool call names for itself (a structured cwd / workdir), else null.
const ownCwd = (input) => {
  const args = typeof input === "string" ? safeJson(input) : input;
  return [args?.cwd, args?.workdir].find((c) => typeof c === "string" && c !== "") ?? null;
};

// ---- The reader: lines in, messages out; can be stopped and resumed ----
// v3 gives every message its place in the file: `seq` (the byte offset of its line) and `blockIndex` (the position of its
// block in that line). The order of messages is (seq, blockIndex, id); a tool run keeps the place of its call, whatever
// line its result came in. Messages are upserted by id, so reading a file in parts gives what reading it whole gives
// (as long as the limits below are not reached): `emitted()` has what this reader made or changed.
export const OPEN_MAX = 64; // calls without a result that a saved state keeps; the oldest fall out and are shown as "unknown"
export const CELLS_MAX = 64; // Codex cells (running scripts) that are followed, and the waits on them
export const WAITS_MAX = 64;
const STATE_TEXT_MAX = 2000; // a saved running call: its text and the number of its files are cut to this
const STATE_FILES_MAX = 100;

export const comparePosition = (a, b) => a.seq - b.seq || a.blockIndex - b.blockIndex || a.id.localeCompare(b.id);

const pairs = (list) => (Array.isArray(list) ? list.filter((e) => Array.isArray(e) && e.length === 2 && typeof e[0] === "string") : []);

// state: what an earlier reader's state() returned (null: a new one). sidechain: whose lines count (the main
// conversation, or a subagent's). initialCwd: the folder known from before these lines. fromStart: whether the lines
// begin at the file's start (a sum of usage is then the whole session's). compact: bound the memory (v3; see the limits
// above and session-meta.mjs createUsageTracker); not compact is exact and unbounded (v2).
// line(text, offset): one complete line; offset = its byte offset in the file, or null (no places, ids as in v2).
// settleOnly(text): only what a line says about calls this reader already has (their results, the waits on Codex cells);
// no messages, no plan, no usage: for lines read only to settle the calls of the part before them.
// conversation(keep): { schemaVersion: 2, cwd, messages (at most `keep`), plan, session }; state(): JSON-safe.
export function createConversationReader(state = null, { sidechain = false, initialCwd = null, fromStart = true, compact = false } = {}) {
  const saved = state && typeof state === "object" && state.v === 1 ? state : null;
  const out = []; // the messages this reader made, in the order of the lines
  const callIdx = new Map(); // call id -> index in out, of the calls made here
  const late = new Map(); // calls of an earlier part that were settled (or given up) here: id -> the changed message
  const open = new Map((Array.isArray(saved?.open) ? saved.open : []).filter((m) => m && typeof m.id === "string").map((m) => [m.id, m])); // running calls
  const cells = new Map(pairs(saved?.cells)); // Codex cell id -> call id
  const waits = new Map(pairs(saved?.waits)); // Codex wait call id -> cell id
  const seen = new Map(); // fallback ids without places: how often a key came up
  const plans = createPlanTracker(saved?.plan ?? null);
  const usage = createUsageTracker({ fromStart: saved ? saved.fromStart !== false : fromStart, compact }, saved?.usage ?? null);
  let cwd = saved ? saved.cwd ?? initialCwd : initialCwd;
  let pos = null; // the offset of the line being read

  const idFor = (own, at, text, blockIndex = 0) => {
    if (typeof own === "string" && own) return own;
    if (pos !== null) return `@${pos}.${blockIndex}`; // the same whichever part of the file was read
    // Never a "|" in an id: the chat uses it to join an id with the rest of its height-cache key.
    const key = `${at ?? ""}~${text.length}~${text.slice(0, 40).replace(/\|/g, "/")}`;
    const n = (seen.get(key) ?? 0) + 1;
    seen.set(key, n);
    return `${key}#${n}`;
  };
  const push = (m, blockIndex = 0) => out.push(pos === null ? m : { ...m, seq: pos, blockIndex });
  // A changed call goes where the call is: in out, or (a call of an earlier part) among the late ones.
  const place = (id, next) => {
    const i = callIdx.get(id);
    if (i !== undefined) out[i] = next;
    else late.set(id, next);
  };
  // The Codex cells of a call and the waits on them (when the call is settled or given up, nothing links to it).
  const unlink = (id) => {
    for (const [cell, callId] of [...cells]) {
      if (callId !== id) continue;
      cells.delete(cell);
      for (const [wait, target] of [...waits]) if (target === cell) waits.delete(wait);
    }
  };
  // A call that can't be followed any more (it fell out of the limits): "unknown" says so; never "running" for ever.
  const giveUp = (id) => {
    const was = open.get(id);
    open.delete(id);
    unlink(id);
    if (was) place(id, { ...was, status: "unknown", finishedAt: null });
  };
  const trim = () => {
    while (open.size > OPEN_MAX) giveUp(open.keys().next().value);
    while (cells.size > CELLS_MAX) {
      const [cell, callId] = cells.entries().next().value;
      cells.delete(cell);
      giveUp(callId);
    }
    while (waits.size > WAITS_MAX) waits.delete(waits.keys().next().value);
  };
  // `name` and `target` (the activity hook's short, safe label) let the office place a subagent at its station.
  const call = (id, name, input, at, blockIndex = 0) => {
    const { text, files } = describe(name, input);
    const target = input !== null && typeof input === "object" ? targetOf(input) : null;
    callIdx.set(id, out.length);
    push({ id, role: "tool", name: String(name), target, text, at, files, status: "running", output: "", startedAt: toMs(at), finishedAt: null, cwd: ownCwd(input) ?? cwd }, blockIndex);
    open.set(id, out[out.length - 1]);
    if (compact) trim();
    plans.call(String(name), id, input, at);
  };
  // `at`: the time of the line that brought the result. The call keeps its own place (seq, blockIndex).
  const settle = (id, status, text, at) => {
    const i = callIdx.get(id);
    const was = i !== undefined ? out[i] : open.get(id);
    if (!was) return;
    const next = { ...was, status, output: clip(String(text ?? "").trim(), OUTPUT_MAX), finishedAt: status === "running" ? null : toMs(at) };
    place(id, next);
    if (status === "running") open.set(id, next);
    else {
      open.delete(id);
      if (compact) unlink(id);
    }
  };

  function read(text, offset, resultsOnly) {
    if (!text || text[0] !== "{") return;
    const d = safeJson(text);
    if (!d || typeof d !== "object") return;
    pos = Number.isSafeInteger(offset) && offset >= 0 ? offset : null;
    const at = d.timestamp ?? null;
    if (!resultsOnly && typeof d.cwd === "string") cwd = d.cwd;

    // Claude Code
    // After /compact Claude writes its summary as the person's turn: one short note instead.
    if (d.type === "user" && d.isCompactSummary) {
      if (!resultsOnly) push({ id: idFor(d.uuid, at, "compacted"), role: "note", text: "Conversation compacted", at });
      return;
    }
    if ((d.type === "user" || d.type === "assistant") && !d.isMeta && Boolean(d.isSidechain) === sidechain) {
      const content = d.message?.content;
      if (d.type === "user") {
        const blocks = typeof content === "string" ? [{ type: "text", text: content }] : Array.isArray(content) ? content : [];
        const results = blocks.filter((b) => b?.type === "tool_result");
        for (const b of results) {
          const text = claudeResultText(b.content);
          settle(b.tool_use_id, b.is_error ? "error" : "ok", text, at);
          if (resultsOnly) continue;
          // The structured result sits on the line itself: it belongs to the result only when there is just one.
          const own = results.length === 1 ? d.toolUseResult : null;
          plans.result(b.tool_use_id, { failed: Boolean(b.is_error), taskId: own?.task?.id ?? null, success: own?.success, text });
        }
        if (resultsOnly) return;
        const raw = blocks.filter((b) => b?.type === "text").map((b) => b.text).join("\n").trim();
        if (INTERRUPTED.test(raw)) push({ id: idFor(d.uuid, at, raw), role: "note", text: "Interrupted by the user", at });
        else {
          // Typed by another agent with hc send: <hc from="t18">…</hc>.
          const sent = raw.match(HC_FROM);
          const typed = userText(sent ? sent[2] : raw);
          if (typed) push({ id: idFor(d.uuid, at, typed), role: "user", text: clip(typed), at, ...(sent ? { from: sent[1] } : {}) });
        }
        return;
      }
      if (resultsOnly) return;
      usage.claudeAssistant(d);
      if (!Array.isArray(content)) return;
      content.forEach((b, i) => {
        if (b?.type === "text" && b.text?.trim()) {
          const text = clip(b.text.trim());
          push({ id: d.uuid ? `${d.uuid}:${i}` : idFor(null, at, text, i), role: "assistant", text, at }, i);
        } else if (b?.type === "tool_use" && b.name) call(b.id || idFor(null, at, b.name, i), b.name, b.input, at, i);
      });
      return;
    }

    // Codex
    if (!resultsOnly) {
      if (d.type === "session_meta") usage.codexMeta(d.payload);
      if (d.type === "turn_context") usage.codexTurn(d.payload);
      if (d.type === "event_msg" && d.payload?.type === "token_count") usage.codexTokens(d.payload, at);
      if (d.type === "session_meta" && typeof d.payload?.cwd === "string") cwd = d.payload.cwd;
      if (d.type === "turn_context" && typeof d.payload?.cwd === "string") cwd = d.payload.cwd;
    }
    if (d.type !== "response_item") return;
    const p = d.payload ?? {};
    if (p.type === "message" && (p.role === "user" || p.role === "assistant")) {
      if (resultsOnly) return;
      const raw = (p.content ?? []).filter((c) => c?.type === "input_text" || c?.type === "output_text").map((c) => c.text).join("\n").trim();
      const typed = p.role === "user" ? userText(raw) : raw;
      if (typed) push({ id: idFor(p.id, at, typed), role: p.role, text: clip(typed), at });
    } else if ((p.type === "function_call" || p.type === "custom_tool_call") && p.name) {
      if (p.name === "wait") {
        const cell = safeJson(p.arguments ?? "")?.cell_id;
        if (cell !== undefined && p.call_id) {
          waits.set(p.call_id, String(cell));
          if (compact) trim();
        }
        return;
      }
      if (resultsOnly) return;
      call(p.call_id || idFor(null, at, p.name), p.name, p.arguments ?? p.input, at);
    } else if (p.type === "function_call_output" || p.type === "custom_tool_call_output") {
      const r = codexResult(p.output);
      const waited = waits.get(p.call_id);
      const id = waited !== undefined ? cells.get(waited) : p.call_id;
      if (r.cell && waited === undefined) {
        cells.set(r.cell, p.call_id);
        if (compact) trim();
      }
      if (id !== undefined) settle(id, r.status, r.text, at);
      // A finished wait is done with (a running one leaves its cell for the next wait).
      if (compact && waited !== undefined && r.status !== "running") waits.delete(p.call_id);
      if (!resultsOnly) plans.result(p.call_id, { failed: r.status === "error", taskId: null, success: undefined, text: r.text });
    }
  }

  const positioned = (list) => list.length > 0 && list.every((m) => Number.isSafeInteger(m.seq));
  // What this reader made or changed: the new messages and the calls of earlier parts it settled, upserts by id, in file order.
  const emitted = () => {
    const byId = new Map();
    for (const m of out) byId.set(m.id, m);
    for (const [id, m] of late) if (!byId.has(id)) byId.set(id, m);
    const all = [...byId.values()];
    return positioned(all) ? all.sort(comparePosition) : all;
  };

  return {
    line: (text, offset = null) => read(text, offset, false),
    settleOnly: (text) => read(text, null, true),
    emitted,
    conversation(keep = KEEP) {
      const messages = positioned(out) || late.size > 0 ? emitted() : out;
      return { schemaVersion: 2, cwd, messages: messages.slice(-keep), plan: plans.plan(), session: usage.session() };
    },
    // Every call that still has no result is given up: shown as "unknown" (a page of old history, whose calls' results lie outside it).
    unsettled: () => open.size,
    unknownOpen() {
      for (const id of [...open.keys()]) giveUp(id);
    },
    cwd: () => cwd,
    plan: () => plans.plan(),
    session: () => usage.session(),
    // What a reader needs to go on from here: JSON-safe, small (see the limits above). Running calls are cut short.
    state() {
      const running = [...open.values()].slice(-OPEN_MAX).map((m) => ({ ...m, text: clip(String(m.text ?? ""), STATE_TEXT_MAX), files: (m.files ?? []).slice(0, STATE_FILES_MAX) }));
      return JSON.parse(JSON.stringify({
        v: 1, cwd, fromStart: saved ? saved.fromStart !== false : fromStart, open: running, cells: [...cells].slice(-CELLS_MAX), waits: [...waits].slice(-WAITS_MAX),
        plan: plans.state(), usage: usage.state(), planSig: saved?.planSig ?? null, sessionSig: saved?.sessionSig ?? null,
      }));
    },
  };
}

// The conversation of a session file's lines: { schemaVersion: 2, cwd, messages (at most `keep`), plan, session }.
// initialCwd: the folder known from before these lines (the file's start, when they are only its tail);
// fromStart: whether the lines begin at the file's start (a sum of usage is then the whole session's).
// The v2 way: no places in the file, ids from the lines' own, no limits.
export function conversationFrom(lines, keep = KEEP, { sidechain = false, initialCwd = null, fromStart = true } = {}) {
  const reader = createConversationReader(null, { sidechain, initialCwd, fromStart });
  for (const line of lines) reader.line(line, null);
  return reader.conversation(keep);
}
