// PolyFlow City agent card MOD: pure functions only. No herdr / gpui-kit, so node can load and test it directly.
// Data handling only; cache reading and drawing live in main.js.

export const JOBS = [
  "corpo",
  "fixer",
  "medtech",
  "netrunner",
  "nomad",
  "rockerboy",
  "solo",
  "techie",
];

// A cache older than this is marked stale: statusLine rewrites it on every response, so 5 minutes without change is not live.
export const STALE_SECONDS = 300;

const JOB_SET = new Set(JOBS);
const SESSIONS_DIR = "data/polyflow-city/sessions";
const PORTRAITS_DIR = "mods/polyflow-agents/art";
const SPRITES_DIR = "mods/polyflow-agents/sprites";
// Jobs that have a full-body animation (generated by tools/sprites/build.mjs); jobs not listed use the portrait on the card.
const SPRITE_JOBS = new Set(JOBS);

// Local terminal id: same rule as the file names written by scripts/polyflow-statusline.mjs; no path characters accepted.
const LOCAL_ID = /^[A-Za-z0-9][A-Za-z0-9_-]*$/;

// Only a finite number in 0-100 counts as a percentage; anything else (null, strings, out of range) is treated as no data.
function pct(value) {
  return typeof value === "number" && Number.isFinite(value) && value >= 0 && value <= 100
    ? value
    : null;
}

// String fields: strip control and bidi control characters, collapse whitespace, trim, at most max characters;
// same rules as scripts/polyflow-statusline.mjs, checked again at read time.
function cleanText(value, max) {
  if (typeof value !== "string") return null;
  const s = value.replace(/[\u0000-\u001f\u007f-\u009f\u2028\u2029\u202a-\u202e\u2066-\u2069]/g, "").replace(/\s+/g, " ").trim();
  return s === "" ? null : [...s].slice(0, max).join("");
}

// Session name (Claude Code /rename), at most 80 characters.
const NAME_MAX = 80;
export function cleanName(value) {
  return cleanText(value, NAME_MAX);
}

// Model and effort names are shorter than the session name: they only need to fit on one card line.
const MODEL_MAX = 40;
function cleanModel(value) {
  return cleanText(value, MODEL_MAX);
}

// Match a tab name to a job: exact match only, case-insensitive, ignoring surrounding whitespace.
// Only own keys are scanned, so prototype-chain names like constructor and __proto__ cannot match by accident.
export function jobFor(name, jobs) {
  if (typeof name !== "string") return null;
  const wanted = name.trim().toLowerCase();
  if (wanted === "") return null;
  if (jobs === null || typeof jobs !== "object" || Array.isArray(jobs)) return null;
  for (const key of Object.keys(jobs)) {
    if (key.trim().toLowerCase() !== wanted) continue;
    const job = jobs[key];
    return typeof job === "string" && JOB_SET.has(job.trim()) ? job.trim() : null;
  }
  return null;
}

// Names of all current tabs in screen order, then any that appear only in agents. New tabs go last so existing tabs keep their job.
export function tabNames(spaces, agents) {
  return [
    ...(spaces ?? []).flatMap((s) => (s.tabs ?? []).map((t) => t.name)),
    ...(agents ?? []).map((a) => a.tab_name),
  ];
}

// Every tab as { id, name }: the spaces' tabs and the agents' tabs (an agent's tab may not be listed yet).
export function tabRefs(spaces, agents) {
  return [
    ...(spaces ?? []).flatMap((s) => (s.tabs ?? []).map((t) => ({ id: t.id, name: t.name }))),
    ...(agents ?? []).map((a) => ({ id: a.tab, name: a.tab_name })),
  ].filter((t) => typeof t.id === "string" && t.id && typeof t.name === "string" && t.name.trim() !== "");
}

const nameKey = (name) => name.trim().toLowerCase();
// The memory also keeps each tab's job under its id, so renaming a tab keeps its character.
const tabKey = (id) => `#${id}`;

// Shared between the mods: the job each name got once, so a character never changes when other tabs come or go.
export const JOBS_MEMORY_KEY = "polyflow-city.jobs";

// Assign jobs: entries in jobs.json win, then the job remembered for the tab itself (`kept["#<tab id>"]`, so a
// renamed tab keeps its character), then the one remembered for the name (`kept`: name -> job); the rest start
// from the name, skipping jobs already taken, and repeat only after all eight are used.
// tabs: [{ id, name }] (tabRefs); without it only names count.
export function assignJobs(names, jobs, kept = {}, tabs = []) {
  const list = [...new Set((names ?? []).filter((n) => typeof n === "string" && n.trim() !== "").map(nameKey))];
  const out = new Map();
  const used = new Set();
  for (const key of list) {
    const job = jobFor(key, jobs);
    if (job) { out.set(key, job); used.add(job); }
  }
  for (const { id, name } of tabs ?? []) {
    const key = nameKey(name);
    const job = kept?.[tabKey(id)];
    if (out.has(key) || !list.includes(key) || typeof job !== "string" || !JOBS.includes(job)) continue;
    out.set(key, job);
    used.add(job);
  }
  for (const key of list) {
    const job = kept?.[key];
    if (out.has(key) || typeof job !== "string" || !JOBS.includes(job)) continue;
    out.set(key, job);
    used.add(job);
  }
  for (const key of list) {
    if (out.has(key)) continue;
    if (used.size >= JOBS.length) used.clear();
    const start = [...key].reduce((n, c) => n + c.codePointAt(0), 0);
    const job = Array.from({ length: JOBS.length }, (_, i) => JOBS[(start + i) % JOBS.length]).find((j) => !used.has(j));
    out.set(key, job);
    used.add(job);
  }
  return out;
}

// The memory to store after an assignment: what was kept plus the new names and tabs (null when nothing is new).
export function rememberJobs(assigned, kept = {}, tabs = []) {
  const byTab = (tabs ?? []).map(({ id, name }) => [tabKey(id), assigned.get(nameKey(name))]).filter(([, job]) => job);
  const fresh = [...assigned, ...byTab].filter(([key, job]) => kept?.[key] !== job);
  return fresh.length ? { ...kept, ...Object.fromEntries(fresh) } : null;
}

export function jobIn(name, assigned) {
  return typeof name === "string" ? assigned.get(nameKey(name)) ?? null : null;
}

// image() only reads paths relative to the Herdr home directory; only the eight known jobs are allowed, to avoid building escaping paths.
export function portraitPath(job) {
  return typeof job === "string" && JOB_SET.has(job) ? `${PORTRAITS_DIR}/${job}.png` : null;
}

// Full-body animation: working = attacking, blocked = hand raised, every other state (done, idle, no state) = resting.
export function spritePath(job, status) {
  if (typeof job !== "string" || !SPRITE_JOBS.has(job)) return null;
  const state = status === "working" || status === "blocked" ? status : "rest";
  return `${SPRITES_DIR}/${job}-${state}.gif`;
}

// Program label: based on the app the agent reports itself (OSC 7501); only these three are recognized; builder has no HP/SP source.
const APPS = new Map([
  ["claude-code", { text: "Claude", builder: false }],
  ["codex", { text: "Codex", builder: true }],
  ["opencode", { text: "OpenCode", builder: true }],
]);
export function appLabel(app) {
  const found = typeof app === "string" ? APPS.get(app) : undefined;
  return found ? { ...found } : null;
}

// The cache is only for local terminals; remote ids (vps/t7) have no local file.
export function cachePath(appHomeDir, address) {
  if (typeof appHomeDir !== "string") return null;
  const base = appHomeDir.replace(/\/+$/, "");
  if (base === "") return null;
  if (typeof address !== "string" || !LOCAL_ID.test(address)) return null;
  return `${base}/${SESSIONS_DIR}/${address}.json`;
}

// Remote agent (imac/t1): its statusLine is written in that machine's default Herdr folder;
// with on set, readTextFile resolves relative paths from that machine's home directory (verified 2026-11-03 with hc file read --on).
const MACHINE = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;
export function remoteCachePath(address) {
  if (typeof address !== "string") return null;
  const parts = address.split("/");
  if (parts.length !== 2 || !MACHINE.test(parts[0]) || !LOCAL_ID.test(parts[1])) return null;
  return { on: parts[0], path: `.config/herdr-app/${SESSIONS_DIR}/${parts[1]}.json` };
}

// Cache content: { updatedAt, contextRemainingPct, fiveHourRemainingPct, sessionName, model, effort }.
// A single bad field only makes that field null; an invalid updatedAt makes the whole file unreadable.
export function parseCache(text) {
  if (typeof text !== "string" || text.trim() === "") return null;
  let data;
  try {
    data = JSON.parse(text);
  } catch {
    return null;
  }
  if (data === null || typeof data !== "object" || Array.isArray(data)) return null;
  const updatedAt = data.updatedAt;
  if (typeof updatedAt !== "number" || !Number.isFinite(updatedAt) || updatedAt < 0) return null;
  return {
    updatedAt,
    hp: pct(data.contextRemainingPct),
    sp: pct(data.fiveHourRemainingPct),
    name: cleanName(data.sessionName),
    model: cleanModel(data.model),
    effort: cleanModel(data.effort),
  };
}

// The "model · effort" line on the card: no model means no line (effort alone is meaningless).
export function modelText(model, effort) {
  const m = cleanModel(model);
  if (m === null) return null;
  const e = cleanModel(effort);
  return e === null ? m : `${m} · ${e}`;
}

// What one HP/SP bar draws: no number (or no timestamp) shows "—" with no fill;
// stale only adds a marker; the number is shown as is, never rewritten to another value.
export function gauge(value, updatedAt, now) {
  const p = pct(value);
  const at =
    typeof updatedAt === "number" && Number.isFinite(updatedAt) && updatedAt >= 0
      ? updatedAt
      : null;
  if (p === null || at === null) return { text: "—", pct: null, stale: false };
  const stale = typeof now === "number" && Number.isFinite(now) && now - at > STALE_SECONDS;
  return { text: `${p}%`, pct: p, stale };
}
